(function(){
  const run = texts=>{ texts.forEach((t, i)=>{ const s = document.createElement('script'); s.textContent = t + '\n//# sourceURL=' + location.href.replace(/[^/]*$/, '') + 'js/' + RUNEFALL_FILES[i]; document.body.appendChild(s); }); };
  // file:// pages can't fetch(); there the files are added as plain <script src> tags instead (same order)
  const tags = ()=>{ RUNEFALL_FILES.forEach(f=>{ const s = document.createElement('script'); s.src = 'js/' + f; s.async = false; document.body.appendChild(s); }); };
  if(location.protocol==='file:'){ tags(); return; }
  Promise.all(RUNEFALL_FILES.map(f=>fetch('js/' + f).then(r=>{ if(!r.ok) throw new Error(f + ' ' + r.status); return r.text(); })))
    .then(run, err=>{ console.error('Runefall loader:', err); tags(); });
})();
